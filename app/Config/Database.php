    public function __construct()
    {
        $defaults = $this->default;
        parent::__construct();

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
            return;
        }

        // Web and CLI must use the same project .env, never a stale process
        // override, alternate group, DSN, or implicit SQLite fallback.
        $values = (new \CodeIgniter\Config\DotEnv(ROOTPATH))->parse() ?? [];
        foreach (['hostname', 'database', 'DBDriver'] as $required) {
            if (trim((string) ($values['database.default.' . $required] ?? '')) === '') {
                throw new \RuntimeException('Configure database.default.' . $required . ' in the project .env file.');
            }
        }
        $this->defaultGroup = 'default';
        $this->default = $defaults;
        foreach ($defaults as $key => $default) {
            if (is_array($default) || $key === 'DSN') {
                continue;
            }
            $value = $values['database.default.' . $key] ?? $default;
            $this->default[$key] = is_bool($default)
                ? filter_var($value, FILTER_VALIDATE_BOOLEAN)
                : (is_int($default) ? (int) $value : (string) $value);
        }
    }
